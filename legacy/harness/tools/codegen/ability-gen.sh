#!/bin/bash
# ============================================================
# ability-gen.sh — Ability (AB/AE) 代码生成工具
#
# 基于 AbilityEditor.cs 模板精确转译
# 生成 6 类文件 + 修改 5-6 类注册文件
#
# 用法:
#   ability-gen.sh --name <Name> --type <AB|AE> \
#     --fields "M_Field1:type1,M_Field2:type2" \
#     --csv-fields "M_Field1,M_Field2" \
#     [--primary-keys "M_Sign"] \
#     --sync-client <true|false> \
#     [--in-fields "In_StartPoint:Vector3"] \
#     [--project-root <path>]
#
# 示例:
#   ability-gen.sh --name Fireball --type AB \
#     --fields "M_Power:int,M_LifeTime:float,M_EffectName:string" \
#     --csv-fields "M_Power,M_LifeTime,M_EffectName" \
#     --primary-keys "M_Sign" \
#     --sync-client true \
#     --in-fields "In_StartPoint:Vector3"
#
# OUTPUT FILES (供 Phase 4 技术文档 S-05 引用):
#   CREATE: Assets/Scripts/Data/Configs/Ability/{AB|AE}/TemplateM/AbilityM_{Name}.cs
#           — M-data 数据类 (字段定义 + CSV 读取)
#   CREATE: Assets/Scripts/Data/Configs/Ability/{AB|AE}/TemplateM/Select/AbilityM_{Name}_Select.cs
#           — Select 缓存类 (主键查询)
#   CREATE: Assets/Scripts/GamePlay/Server/Ability/System/S{AB|AE}/S{AB|AE}_{Name}System.cs
#           — 服务端 Ability System (S_Ability_Base)
#   CREATE: Assets/Scripts/GamePlay/Client/Ability/System/C{AB|AE}/C{AB|AE}_{Name}System.cs
#           — 客户端 Ability System (条件: --sync-client true)
#   CREATE: Assets/Scripts/Message/Network/Ability/{AB|AE}/Rpc_{Name}.cs
#           — RPC 消息定义
#   CREATE: Assets/Bundle/Configs/Ability/{AB|AE}/AbilityM_{Name}.csv
#           — CSV 数据模板 (空行，需手动填数据)
#   MODIFY: Assets/Scripts/Data/Configs/Ability/{AbilityConfig|AbilityEffectConfig}_AutoGenerated.cs
#           — ConfigId 常量 + Init() 注册 (×2 插入点)
#   MODIFY: Assets/Scripts/Message/Network/{14|15}_Proto_Ability{AB|AE}_Auto.cs
#           — RPC 枚举 + Handler case + Register 注册 (×3 插入点)
#   MODIFY: Assets/Scripts/GamePlay/Server/Ability/ServerAbilityManager_Switch{AB|AE}.cs
#           — switch case 分支
#   MODIFY: Assets/Scripts/GamePlay/Client/Ability/ClientAbilityManager_Switch{AB|AE}.cs
#           — switch case 分支 (条件: --sync-client true)
# ============================================================
