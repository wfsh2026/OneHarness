    [[ ! -f "$ABILITY_M_FILE" ]] && echo "❌ M 模板文件不存在: $ABILITY_M_FILE" && exit 1
    echo "🔄 regen-select：从 CSV + M 模板重建字段数组"
    # 1. 从 CSV 头部重建 CSV_FIELD_LIST（跳过 ID / RowSign）
    CSV_FIELD_LIST=()
    # 剥离 UTF-8 BOM（0xEF 0xBB 0xBF）并去除行末 CR
    csv_header=$(head -1 "$CSV_FILE" | LC_ALL=C sed 's/^\xef\xbb\xbf//' | tr -d '\r')
    IFS=',' read -ra raw_headers <<< "$csv_header"
    for col in "${raw_headers[@]}"; do
        col=$(echo "$col" | tr -d '\r\n ')
        [[ "$col" == "ID" || "$col" == "RowSign" ]] && continue
        CSV_FIELD_LIST+=("$col")
    done
    # 2. 从 M 模板 .cs grep 各字段类型，重建 FIELD_NAMES / FIELD_TYPES
    FIELD_NAMES=()
    FIELD_TYPES=()
    for csv_f in "${CSV_FIELD_LIST[@]}"; do
        # 防御：grep 无匹配返回 1，加 || true 避免 set -e 提前退出
        f_type=$(grep -oE "public [a-zA-Z0-9_]+ ${csv_f};" "$ABILITY_M_FILE" 2>/dev/null \
            | awk '{print $2}' | head -1) || true
        if [[ -z "$f_type" ]]; then
            echo "⚠️  字段 ${csv_f} 未在 M 模板中找到类型，默认 float"
            f_type="float"
        fi
        FIELD_NAMES+=("$csv_f")
        FIELD_TYPES+=("$f_type")
    done
    # 3. 重新注入 M_Sign（CSV 中无此列，但 Select 的 CopyInstanceData 需要）
    HAS_M_SIGN_RS=false
    for fn in "${FIELD_NAMES[@]}"; do
        [[ "$fn" == "M_Sign" ]] && HAS_M_SIGN_RS=true && break
    done
    if [[ "$HAS_M_SIGN_RS" == "false" ]]; then
        FIELD_NAMES=("M_Sign" "${FIELD_NAMES[@]}")
        FIELD_TYPES=("string" "${FIELD_TYPES[@]}")
    fi
    echo "   字段列表: ${FIELD_NAMES[*]}"
    echo "   CSV 字段: ${CSV_FIELD_LIST[*]}"
fi

