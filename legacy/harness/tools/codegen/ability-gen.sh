    # 读取 CSV 头部，确认 ID 和 RowSign 列的索引（剥离 UTF-8 BOM 和 CR）
    csv_header=$(head -1 "$CSV_FILE" | LC_ALL=C sed 's/^\xef\xbb\xbf//' | tr -d '\r')
    IFS=',' read -ra csv_cols <<< "$csv_header"
    id_col=-1
    sign_col=-1
    for ci in "${!csv_cols[@]}"; do
        col="${csv_cols[$ci]}"
        [[ "$col" == "ID" ]] && id_col=$ci
        [[ "$col" == "RowSign" ]] && sign_col=$ci
    done
    if [[ $id_col -lt 0 || $sign_col -lt 0 ]]; then
        echo "❌ CSV 头部未找到 ID 或 RowSign 列（实际: $csv_header）"
        exit 1
    fi

    # 生成 ID 常量块和 Sign 常量块
    id_block=""
    sign_block=""
    while IFS= read -r row || [[ -n "$row" ]]; do
        [[ -z "$row" ]] && continue
        IFS=',' read -ra cells <<< "$row"
        row_id="${cells[$id_col]}"
        row_sign="${cells[$sign_col]}"
        [[ -z "$row_id" || -z "$row_sign" ]] && continue
        id_block="${id_block}        public const byte ID_${row_sign} = ${row_id};"$'\n'
        sign_block="${sign_block}        public const string Sign_${row_sign} = \"${row_sign}\";"$'\n'
    done < <(tail -n +2 "$CSV_FILE")

    if [[ -z "$id_block" && -z "$sign_block" ]]; then
        echo "⚠️  CSV 中没有数据行，常量块为空，跳过更新"
        exit 0
    fi

    # 将占位符替换为常量块（用 awk 逐行处理，避免 sed 多行问题）
    tmp_select="${SELECT_FILE}.tmp.$$"
    awk \
        -v id_blk="$id_block" \
        -v sign_blk="$sign_block" \
        '{
            if ($0 ~ /\/\/ \[ID_CONSTANTS_PLACEHOLDER\]/) {
                # 移除尾随换行，然后输出常量块
                printf "%s", id_blk
                next
            }
            if ($0 ~ /\/\/ \[SIGN_CONSTANTS_PLACEHOLDER\]/) {
                printf "%s", sign_blk
                next
            }
            print
        }' "$SELECT_FILE" > "$tmp_select"
    mv "$tmp_select" "$SELECT_FILE"

    echo "✅ 已更新常量："
    echo "$id_block"
    echo "$sign_block"
    echo "   文件: $SELECT_FILE"
    exit 0
fi



# 在第一个匹配 pattern 的行之前插入多行文本（跨平台）
insert_before() {
    local pattern="$1"
    local text="$2"
    local file="$3"
    local tmp="${file}.tmp.$$"
    local txt_file="${file}.ins.$$"
    printf '%s\n' "$text" > "$txt_file"
    awk -v pat="$pattern" -v tf="$txt_file" '
        !done && $0 ~ pat {
            while ((getline line < tf) > 0) print line
            done = 1
        }
        { print }
    ' "$file" > "$tmp"
    mv "$tmp" "$file"
    rm -f "$txt_file"
}

# 在最后一个匹配 pattern 的行之后插入多行文本
insert_after_last() {
    local pattern="$1"
    local text="$2"
    local file="$3"
    local tmp="${file}.tmp.$$"
    local last_line
    last_line=$(grep -n "$pattern" "$file" | tail -1 | cut -d: -f1)
    if [[ -n "$last_line" ]]; then
        local txt_file="${file}.ins.$$"
        printf '%s\n' "$text" > "$txt_file"
        awk -v ln="$last_line" -v tf="$txt_file" '
            NR==ln { print; while ((getline line < tf) > 0) print line; next }
            { print }
        ' "$file" > "$tmp"
        mv "$tmp" "$file"
        rm -f "$txt_file"
    else
        echo "⚠️  未找到匹配: $pattern in $file"
    fi
}

# 解析字段列表 "M_Power:int,M_LifeTime:float" 为数组
# 结果存入全局 _PARSED_NAMES / _PARSED_TYPES（兼容 bash 3.2，无 local -n）
parse_fields() {
    local input="$1"
    _PARSED_NAMES=()
    _PARSED_TYPES=()
    IFS=',' read -ra pairs <<< "$input"
    for pair in "${pairs[@]}"; do
        IFS=':' read -r fname ftype <<< "$pair"
        _PARSED_NAMES+=("$fname")
        _PARSED_TYPES+=("$ftype")
    done
}

# C# 类型到 AssetCsvManager 解析代码
csv_parse_expr() {
    local fname="$1"
    local ftype="$2"
    if [[ "$ftype" == "string" ]]; then
        echo "AssetCsvManager.GetCsvRowValue(row, \"${fname}\")"
    else
        echo "AssetCsvManager.ParseValue<${ftype}>(AssetCsvManager.GetCsvRowValue(row, \"${fname}\"))"
    fi
}

# C# 类型到 ByteBuffer 读取方法
buffer_read_method() {
    local ftype="$1"
    case "$ftype" in
        int)      echo "ReadInt" ;;
        uint)     echo "ReadUInt" ;;
        short)    echo "ReadShort" ;;
        ushort)   echo "ReadUShort" ;;
        long)     echo "ReadLong" ;;
        ulong)    echo "ReadULong" ;;
        float)    echo "ReadFloat" ;;
        double)   echo "ReadDouble" ;;
        byte)     echo "ReadByte" ;;
        sbyte)    echo "ReadSByte" ;;
        bool)     echo "ReadBool" ;;
        string)   echo "ReadString" ;;
        Vector3)  echo "ReadVector3" ;;
        Vector2)  echo "ReadVector2" ;;
        Quaternion) echo "ReadQuaternion" ;;
        *)        echo "Read /* TODO: unknown type $ftype */" ;;
    esac
}

